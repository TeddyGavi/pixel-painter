#!/usr/bin/env python3
"""Generate main/palette_<id>.c from palettes/<id>.tsv (the source of truth).

usage: python3 palettes/gen_palettes.py            # regenerates every palettes/*.tsv
TSV columns: code r g b name source note  (lines starting with # are comments)
source = label (RGB printed by the manufacturer) | photo (sampled, approximate)."""
import colorsys, csv, glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from colorname import FAMILIES, family

HERE = os.path.dirname(os.path.abspath(__file__))
MAIN = os.path.join(HERE, '..', 'main')


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def gen(tsv):
    pid = os.path.splitext(os.path.basename(tsv))[0]          # e.g. artkal_s
    sym = pid.upper()                                          # ARTKAL_S
    rows = list(csv.DictReader((l for l in open(tsv) if not l.startswith('#')), delimiter='\t'))
    codes = [r['code'] for r in rows]
    assert len(codes) == len(set(codes)), 'duplicate codes in ' + tsv
    assert len(rows) < 255, 'cells store a uint8_t index; 0xFF = empty'
    out = os.path.join(MAIN, 'palette_%s.c' % pid)
    with open(out, 'w') as o:
        o.write('// GENERATED by palettes/gen_palettes.py from palettes/%s. Do not edit;\n' % os.path.basename(tsv))
        o.write('// edit the TSV and regenerate. See palettes/README.md for the data source.\n')
        o.write('#include "palette_%s.h"\n\n' % pid)
        o.write('const bead_color_t %s[%d] = {\n' % (sym, len(rows)))
        for r in rows:
            R, G, B = int(r['r']), int(r['g']), int(r['b'])
            assert all(0 <= v <= 255 for v in (R, G, B)), r
            approx = 1 if r['source'] == 'photo' else 0
            fam = family(R, G, B)
            r['_fam'] = fam
            r['_light'] = colorsys.rgb_to_hls(R / 255, G / 255, B / 255)[1]
            r['_approx'] = approx
            o.write('    { %-24s %-8s RGB565(%3d, %3d, %3d), %d, %d },\n' %
                    (c_str(r['name']) + ',', c_str(r['code']) + ',', R, G, B, approx, fam))
        o.write('};\n\n')
        # Browse order on the device: by family, solids before specialty beads,
        # then light to dark. Family jump = move to the next family in this order.
        order = sorted(range(len(rows)), key=lambda i: (rows[i]['_fam'], rows[i]['_approx'],
                                                        -rows[i]['_light'], i))
        o.write('// Browse order (palette indices), grouped by family: %s\n' % ', '.join(
            '%s %d' % (FAMILIES[f], sum(1 for r in rows if r['_fam'] == f)) for f in range(len(FAMILIES))))
        o.write('const uint8_t %s_ORDER[%d] = {\n' % (sym, len(rows)))
        for i in range(0, len(order), 16):
            o.write('    ' + ', '.join('%3d' % v for v in order[i:i + 16]) + ',\n')
        o.write('};\n')
    hdr = os.path.join(MAIN, 'palette_%s.h' % pid)
    with open(hdr, 'w') as o:
        o.write('// GENERATED by palettes/gen_palettes.py. Do not edit.\n#pragma once\n')
        o.write('#include "palettes.h"\n#define %s_COUNT %d\n' % (sym, len(rows)))
        o.write('extern const bead_color_t %s[%s_COUNT];\n' % (sym, sym))
        o.write('extern const uint8_t %s_ORDER[%s_COUNT];   // browse order\n' % (sym, sym))
    print('%s: %d colours -> %s' % (pid, len(rows), os.path.relpath(out)))


# Brand key used in export URLs (palettes.c palette_t.key) for each TSV.
WEB_KEYS = {'artkal_s': 'artkal', 'hama': 'hama', 'miyuki_delica': 'miyuki', 'toho_round': 'toho', 'preciosa_rocailles': 'preciosa'}


def gen_web_names(tsvs):
    """web/names.js: code -> name per brand, for the QR export page (names only; the
    URL itself carries codes and colours, so the page works without this table)."""
    import json
    names = {}
    for tsv in tsvs:
        pid = os.path.splitext(os.path.basename(tsv))[0]
        if pid not in WEB_KEYS: continue
        rows = csv.DictReader((l for l in open(tsv) if not l.startswith('#')), delimiter='\t')
        names[WEB_KEYS[pid]] = {r['code']: r['name'] for r in rows}
    out = os.path.join(HERE, '..', 'web', 'names.js')
    with open(out, 'w') as o:
        o.write('// GENERATED by palettes/gen_palettes.py from palettes/*.tsv. Do not edit.\n')
        o.write('window.BEAD_NAMES = ' + json.dumps(names, separators=(',', ':')) + ';\n')
    print('web names: %s -> %s' % (', '.join('%s %d' % (k, len(v)) for k, v in names.items()),
                                   os.path.relpath(out)))


TSVS = sorted(glob.glob(os.path.join(HERE, '*.tsv')))
for t in TSVS:
    gen(t)
gen_web_names(TSVS)
